"""Lab 51: instruction tuning. Same knowledge, three data styles, and the FLAN lesson about templates."""
import itertools, sys, tempfile
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src"), str(ROOT / "labs")]
from _sft_tasks import accuracy, build_model, load_adapter, sft, write_jsonl  # noqa: E402

RULE = {"leaks": "two", "jams": "one", "overheats": "four", "fails": "three"}
TRAIN_SUBJ = ["pump", "valve", "motor"]
TEST_SUBJ = ["bearing", "gauge", "seal", "filter"]          # never seen during training
# the diverse set varies WORD ORDER, not just wording: the fault verb appears last, first and middle
TEMPLATES = ["the {s} {v}", "report : {s} {v}", "{v} on the {s}", "{v} : machine {s} today",
             "status of {s} : {v}"]
UNSEEN_TEMPLATE = "{v} was reported on our {s} unit"         # verb FIRST, phrasing never seen
CANDS = [f"severity {w}" for w in ("one", "two", "three", "four")]
tmp = Path(tempfile.mkdtemp())
corpus = [t.format(s=s, v=v) for t in TEMPLATES + [UNSEEN_TEMPLATE]
          for s, v in itertools.product(TRAIN_SUBJ + TEST_SUBJ, RULE)] + CANDS
model_dir = build_model(tmp / "base", corpus, hidden=128, layers=3)


def rows(templates):
    out = []
    for t in templates:
        for s, v in itertools.product(TRAIN_SUBJ, RULE):
            out.append({"messages": [{"role": "user", "content": t.format(s=s, v=v)},
                                     {"role": "assistant", "content": f"severity {RULE[v]}"}]})
    return out


def items(template, subjects):
    return [{"messages": [{"role": "user", "content": template.format(s=s, v=v)}],
             "answer": f"severity {RULE[v]}", "candidates": CANDS}
            for s, v in itertools.product(subjects, RULE)]


print("Task: map a fault verb to a severity. Train on 3 machines, test on 4 machines never seen.")
print("Both runs see the SAME 12 facts; only the number of phrasings differs.\n")
print(f"{'training data':<34}{'rows':>6}{'seen template':>15}{'UNSEEN template':>17}{'unseen subj+template':>22}")
for name, tpl in [("1 template (Alpaca-style, narrow)", TEMPLATES[:1]),
                  ("5 templates (FLAN-style, diverse)", TEMPLATES)]:
    data = rows(tpl) * (5 if len(tpl) == 1 else 1)          # same number of gradient steps for both
    # enough steps for a 3-layer model to actually learn the rule (10 epochs was not: everything sat at chance)
    f = write_jsonl(data, tmp / f"{len(tpl)}.jsonl")
    adapter, _ = sft(model_dir, f, tmp / f"run{len(tpl)}", epochs=60, lr=5e-3, r=32)
    m, tok = load_adapter(model_dir, adapter)
    seen = accuracy(m, tok, items(TEMPLATES[0], TRAIN_SUBJ))
    unseen_t = accuracy(m, tok, items(UNSEEN_TEMPLATE, TRAIN_SUBJ))
    unseen_both = accuracy(m, tok, items(UNSEEN_TEMPLATE, TEST_SUBJ))
    print(f"{name:<34}{len(data):>6}{seen:>15}{unseen_t:>17}{unseen_both:>22}")
print("  (chance = 0.25)")

print("\nThe three instruction-data styles, same content:")
print("""  FLAN     : many EXISTING tasks recast into many templates. 2022 collection = 1836 tasks (Apache-2.0).
             Lesson from its paper: held-out performance rises log-linearly with the number of tasks.
  Alpaca   : 52K instruction/input/output records generated by an LLM from 175 human seeds.
             Cheap and hugely influential, but licensed CC BY-NC 4.0 - NOT for commercial use.
  OpenHermes-style: large multi-source chat collections in messages format, mostly synthetic,
             compiled from many upstream datasets. Check the dataset card for size and licence
             before use: the licence of a compilation is only as permissive as its worst source.""")
print("\nPractical rule: diversity of TASKS and PHRASINGS buys robustness; volume of one template buys")
print("memorisation. If your users can phrase a request five ways, your data must contain five ways.")
